const uint8_t * uih_font_glyph(char c) {
    const uint8_t * unknown = NULL;
    for (size_t i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); ++i) {
        if (GLYPHS[i].c == c) {
            return GLYPHS[i].columns;
        }
        if (GLYPHS[i].c == '?') {
            unknown = GLYPHS[i].columns;
        }
    }
    return unknown;
}
